export function buildVerseDevotionReferenceMessages({ ref, verseText, mode = 'fast' }) {
  const depthGuide = mode === 'deep'
    ? '깊이 모드다. 해설은 8~10문장, 묵상은 7~9문장, 기도문은 8~10문장으로 충분히 묵상해서 작성한다.'
    : '일반 모드다. 해설은 6~8문장, 묵상은 5~7문장, 기도문은 6~8문장으로 작성한다.';

  return [
    {
      role: 'system',
      content: `${VERSE_DEVOTION_REFERENCE_STYLE_GUIDE}\n\n${depthGuide}`,
    },
    {
      role: 'user',
      content: `본문 위치: ${ref}\n본문: ${verseText}\n\n위 본문에 대한 해설, 묵상, 기도문을 작성하라.\n\n작성 전 내부적으로 점검하라.\n- 본문 위치와 본문을 바꾸지 않았는가?\n- 해설이 본문 문맥과 직접 연결되어 있는가?\n- 해설의 문장 종결이 정중한 존댓말로 통일되어 있는가?\n- 묵상이 1인칭 고백형이며 모든 서술어가 “합니다/습니다”체인가?\n- “저는 … 생각한다/바란다/싶다”처럼 주어와 서술어의 높임말이 충돌하지 않는가?\n- 기도문이 “아버지,”로 시작하고 정해진 문장으로 끝나는가?\n- 고난이나 질병을 개인의 죄 때문이라고 단정하지 않았는가?\n- 공통 템플릿처럼 보이지 않고 이 구절에 맞게 작성되었는가?\n\n점검 후 JSON만 출력하라.`,
    },
  ];
}
